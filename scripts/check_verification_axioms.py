#!/usr/bin/env python3
"""Reject unexpected axioms in Lean's `#print axioms` audit output."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from verification_source_declarations import declared_namespaces, theorem_declarations


ALLOWED_AXIOMS = {"propext", "Classical.choice", "Quot.sound"}
RECORD_START = re.compile(
    r"^'([^']+)' (?:depends on axioms: \[(.*)|does not depend on any axioms)$"
)


def finite_audit_name(name: str) -> bool:
    """Names that explicitly identify finite checks, examples, or boundaries."""
    normalized = name.lower()
    return (
        name.endswith("Check_passes")
        or "_example" in name
        or "boundedinput" in normalized
        or "_bounded_agrees_with" in normalized
        or "boundaryinput" in normalized
        or "widevalueinput" in normalized
        or re.search(r"_for_[a-z0-9]*input$", normalized) is not None
        or name.endswith("_boundary")
        or "_boundary_" in normalized
    ) and name != "mergeLoopStep_preserves_boundary"


def is_registered_native_decide_axiom(axiom: str, finite_targets: set[str]) -> bool:
    """Accept helpers generated by a registered finite target in this group."""
    targets = "|".join(re.escape(target) for target in sorted(finite_targets))
    pattern = re.compile(
        r"^(?:_private\..+\.\d+\.)?(?:"
        + targets
        + r")\._native\.native_decide\.ax_[0-9_]+$"
    )
    return pattern.fullmatch(axiom) is not None


def parse_report(path: Path) -> list[tuple[str, set[str]]]:
    lines = path.read_text(encoding="utf-8").splitlines()
    records: list[tuple[str, set[str]]] = []
    index = 0
    while index < len(lines):
        match = RECORD_START.match(lines[index])
        if not match:
            if not lines[index].strip():
                index += 1
                continue
            raise ValueError(
                f"{path}:{index + 1}: unrecognized kernel-axiom audit output"
            )

        theorem = match.group(1)
        payload = match.group(2)
        if payload is None:
            records.append((theorem, set()))
            index += 1
            continue
        index += 1
        while "]" not in payload and index < len(lines):
            payload += " " + lines[index].strip()
            index += 1
        if "]" not in payload:
            raise ValueError(f"{path}: unterminated axiom list for {theorem}")

        axiom_text = payload.split("]", maxsplit=1)[0]
        axioms = {axiom.strip() for axiom in axiom_text.split(",") if axiom.strip()}
        records.append((theorem, axioms))

    if not records:
        raise ValueError(f"{path}: no `#print axioms` records found")
    return records


def main(arguments: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--manifest",
        required=True,
        help="JSON map from audit groups to their exact theorem names",
    )
    parser.add_argument(
        "--audit",
        action="append",
        nargs=2,
        metavar=("GROUP", "REPORT"),
        default=[],
        help="check REPORT against GROUP in the manifest (repeatable)",
    )
    parser.add_argument(
        "--native-decide-group",
        action="append",
        default=[],
        metavar="GROUP",
        help="allow native_decide helpers from registered targets in this finite-check group",
    )
    parser.add_argument(
        "--finite-source",
        action="append",
        nargs=3,
        metavar=("GROUP", "SOURCE", "NAMESPACE"),
        default=[],
        help="require finite targets in SOURCE/NAMESPACE to be registered in GROUP",
    )
    parser.add_argument(
        "--general-source",
        action="append",
        nargs=3,
        metavar=("GROUP", "SOURCE", "NAMESPACE"),
        default=[],
        help="require general theorems in SOURCE/NAMESPACE to be registered in GROUP",
    )
    parser.add_argument(
        "--finite-root",
        action="append",
        default=[],
        metavar="DIRECTORY",
        help="require every Lean file under DIRECTORY to have a --finite-source entry",
    )
    parser.add_argument(
        "--general-root",
        action="append",
        default=[],
        metavar="DIRECTORY",
        help="require every Lean file under DIRECTORY to have a --general-source entry",
    )
    parser.add_argument(
        "--github-summary",
        metavar="PATH",
        help="append a proof-scope and native-dependency summary for GitHub Actions",
    )
    options = parser.parse_args(arguments)
    if not options.audit:
        parser.error("at least one --audit GROUP REPORT is required")

    try:
        manifest = json.loads(Path(options.manifest).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        parser.error(f"cannot read manifest: {error}")
    if not isinstance(manifest, dict) or not manifest:
        parser.error("manifest must contain at least one audit group")
    for group, theorems in manifest.items():
        if not isinstance(group, str) or not group.strip():
            parser.error("manifest group names must be non-empty strings")
        if not isinstance(theorems, list) or not theorems:
            parser.error(f"manifest group {group!r} must contain theorem names")
        if not all(isinstance(theorem, str) and theorem.strip() for theorem in theorems):
            parser.error(f"manifest group {group!r} contains an empty or invalid theorem name")
        if len(set(theorems)) != len(theorems):
            parser.error(f"manifest group {group!r} contains duplicate theorem names")

    groups: set[str] = set()
    reports: set[str] = set()
    for group, filename in options.audit:
        if group not in manifest:
            parser.error(f"unknown audit group in manifest: {group}")
        if group in groups:
            parser.error(f"duplicate audit group: {group}")
        if filename in reports:
            parser.error(f"duplicate audit report: {filename}")
        groups.add(group)
        reports.add(filename)
    missing_groups = set(manifest) - groups
    if missing_groups:
        parser.error("manifest groups not checked: " + ", ".join(sorted(missing_groups)))
    native_decide_groups = set(options.native_decide_group)
    unknown_native_groups = native_decide_groups - set(manifest)
    if unknown_native_groups:
        parser.error(
            "unknown native_decide groups: " + ", ".join(sorted(unknown_native_groups))
        )
    unaudited_native_groups = native_decide_groups - groups
    if unaudited_native_groups:
        parser.error(
            "native_decide groups not audited: " + ", ".join(sorted(unaudited_native_groups))
        )
    native_decide_targets = set().union(
        *(set(manifest[group]) for group in native_decide_groups)
    ) if native_decide_groups else set()

    finite_sources: dict[str, set[str]] = {}
    finite_source_paths: set[Path] = set()
    for group, filename, namespace in options.finite_source:
        if group not in native_decide_groups:
            parser.error(f"finite source group lacks native_decide policy: {group}")
        if group not in manifest:
            parser.error(f"unknown finite source group: {group}")
        path = Path(filename)
        finite_source_paths.add(path.resolve())
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except OSError as error:
            parser.error(f"cannot read finite source {path}: {error}")
        if namespace not in declared_namespaces(lines):
            parser.error(f"{path}: expected namespace {namespace!r}")
        try:
            discovered = {
                f"{declared_namespace}.{name}"
                for declared_namespace, name, is_private in theorem_declarations(lines)
                if not is_private and finite_audit_name(name)
            }
        except ValueError as error:
            parser.error(f"{path}: cannot safely scan theorem declarations: {error}")
        finite_sources.setdefault(group, set()).update(discovered)

    for directory in options.finite_root:
        root = Path(directory)
        try:
            source_files = {path.resolve() for path in root.rglob("*.lean")}
        except OSError as error:
            parser.error(f"cannot scan finite source root {root}: {error}")
        unregistered_sources = source_files - finite_source_paths
        if unregistered_sources:
            parser.error(
                f"Lean sources under {root} lack --finite-source entries: "
                + ", ".join(str(path) for path in sorted(unregistered_sources))
            )

    for group, discovered in finite_sources.items():
        registered = set(manifest[group])
        missing = discovered - registered
        stale = registered - discovered
        if missing:
            parser.error(
                f"finite targets missing from {group}: " + ", ".join(sorted(missing))
            )
        if stale:
            parser.error(
                f"finite manifest entries not found in sources for {group}: "
                + ", ".join(sorted(stale))
            )

    general_sources: dict[str, set[str]] = {}
    private_sources: dict[str, set[str]] = {}
    general_source_paths: set[Path] = set()
    for group, filename, namespace in options.general_source:
        if group not in manifest:
            parser.error(f"unknown general source group: {group}")
        path = Path(filename)
        general_source_paths.add(path.resolve())
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except OSError as error:
            parser.error(f"cannot read general source {path}: {error}")
        if namespace not in declared_namespaces(lines):
            parser.error(f"{path}: expected namespace {namespace!r}")
        try:
            declarations = list(theorem_declarations(lines))
        except ValueError as error:
            parser.error(f"{path}: cannot safely scan theorem declarations: {error}")
        discovered = {
            f"{declared_namespace}.{name}"
            for declared_namespace, name, is_private in declarations
            if not is_private and not finite_audit_name(name)
        }
        general_sources.setdefault(group, set()).update(discovered)
        private_discovered = {
            f"{declared_namespace}.{name}"
            for declared_namespace, name, is_private in declarations
            if is_private
        }
        private_group = f"{group}_private"
        if private_discovered and private_group not in manifest:
            parser.error(f"private theorem source has no audit group: {private_group}")
        if private_group in manifest:
            private_sources.setdefault(private_group, set()).update(private_discovered)

    for directory in options.general_root:
        root = Path(directory)
        try:
            source_files = {path.resolve() for path in root.rglob("*.lean")}
        except OSError as error:
            parser.error(f"cannot scan general source root {root}: {error}")
        unregistered_sources = source_files - general_source_paths
        if unregistered_sources:
            parser.error(
                f"Lean sources under {root} lack --general-source entries: "
                + ", ".join(str(path) for path in sorted(unregistered_sources))
            )
        stale_sources = general_source_paths - source_files
        if stale_sources:
            parser.error(
                f"--general-source entries are outside {root} or no longer exist: "
                + ", ".join(str(path) for path in sorted(stale_sources))
            )

    for group, discovered in general_sources.items():
        registered = set(manifest[group])
        native_group = f"{group}_native"
        if native_group in manifest:
            registered.update(manifest[native_group])
        missing = discovered - registered
        stale = registered - discovered
        if missing:
            parser.error(
                f"general targets missing from {group}: " + ", ".join(sorted(missing))
            )
        if stale:
            parser.error(
                f"general manifest entries not found in sources for {group}: "
                + ", ".join(sorted(stale))
            )

    for group, discovered in private_sources.items():
        registered = set(manifest[group])
        missing = discovered - registered
        stale = registered - discovered
        if missing:
            parser.error(
                f"private theorems missing from {group}: " + ", ".join(sorted(missing))
            )
        if stale:
            parser.error(
                f"private manifest entries not found in sources for {group}: "
                + ", ".join(sorted(stale))
            )

    failed = False
    total = 0
    classified_counts = {
        (scope, native): 0
        for scope in ("general", "finite")
        for native in (False, True)
    }
    for group, filename in options.audit:
        path = Path(filename)
        try:
            records = parse_report(path)
        except (OSError, ValueError) as error:
            print(error, file=sys.stderr)
            failed = True
            continue

        if group.endswith("_private"):
            registered = set(manifest[group])
            normalized_records = []
            for theorem, axioms in records:
                if theorem not in registered:
                    candidates = [target for target in registered if theorem.endswith(target)]
                    if len(candidates) == 1:
                        theorem = candidates[0]
                normalized_records.append((theorem, axioms))
            records = normalized_records

        theorem_names = [theorem for theorem, _ in records]
        if len(set(theorem_names)) != len(theorem_names):
            print(f"{path}: duplicate theorem records found", file=sys.stderr)
            failed = True
        expected_names = set(manifest[group])
        actual_names = set(theorem_names)
        missing_names = expected_names - actual_names
        extra_names = actual_names - expected_names
        if missing_names:
            print(
                f"{path}: missing audited theorems: " + ", ".join(sorted(missing_names)),
                file=sys.stderr,
            )
            failed = True
        if extra_names:
            print(
                f"{path}: unregistered audited theorems: " + ", ".join(sorted(extra_names)),
                file=sys.stderr,
            )
            failed = True
        total += len(records)

        for theorem, axioms in records:
            if not group.endswith("_private"):
                scope = "finite" if group.endswith("_finite") else "general"
                has_native_dependency = any(
                    is_registered_native_decide_axiom(axiom, native_decide_targets)
                    for axiom in axioms
                )
                classified_counts[(scope, has_native_dependency)] += 1
            unexpected = axioms - ALLOWED_AXIOMS
            if group in native_decide_groups:
                unexpected = {
                    axiom for axiom in unexpected
                    if not is_registered_native_decide_axiom(axiom, native_decide_targets)
                }
            if unexpected:
                print(
                    f"{theorem}: unexpected axiom dependencies: "
                    + ", ".join(sorted(unexpected)),
                    file=sys.stderr,
                )
                failed = True

    if failed:
        return 1
    if options.github_summary:
        summary_path = Path(options.github_summary)
        summary = [
            "## Lean verification trust summary",
            "",
            "| Proof scope | Native-computation helper dependency | Theorems |",
            "| --- | --- | ---: |",
            f"| General (A) | No | {classified_counts[('general', False)]} |",
            f"| General (B) | Yes | {classified_counts[('general', True)]} |",
            f"| Finite checks (C) | No | {classified_counts[('finite', False)]} |",
            f"| Finite checks (C) | Yes | {classified_counts[('finite', True)]} |",
            "",
            "A/B describe general theorems; C identifies bounded checks. The trust-dependency column is reported independently.",
            "",
        ]
        try:
            with summary_path.open("a", encoding="utf-8") as summary_file:
                summary_file.write("\n".join(summary))
        except OSError as error:
            print(
                f"cannot write GitHub Actions summary {summary_path}: {error}",
                file=sys.stderr,
            )
            return 1
    print(
        f"All {total} registered theorems passed their kernel-axiom policies "
        "(native_decide helpers are limited to explicitly registered targets)."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
